// 국호 판 폰트 서브셋 생성기(개발용, 번들에 포함되지 않음).
// 사용: node resources/js/game/tools/build_plaque_fonts.mjs [--extra <id>:<글자>]...   (프로젝트 루트에서, 네트워크 필요)
// 1) database/data/shelf_territories.json 의 factions[].plaque.native(+native_script/native_lang)·plaque.text(+script) 글자를 폰트 id 별로 모은다
//    (id 매핑 = resources/js/game/ui/plaqueFontMap.js, 단일 지점).
// 2) Google Fonts CSS2 API 의 text= 서브셋(필요 글자만, 아랍 문자는 셰이핑 형태 포함)으로 woff2 를 받아 public/fonts/plaque/<id>.woff2 로 자체 호스팅.
// 3) resources/js/game/data/plaque_fonts.json 에 { fonts: { <id>: { file, chars, bytes, google } } } 기록(런타임이 로드·커버리지 확인에 사용).
// 데이터에 국호가 추가·변경되면 다시 실행한다. 폰트 라이선스: SIL OFL 1.1(Noto).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { PLAQUE_FONTS, plaqueFontId, nfc } from '../ui/plaqueFontMap.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../../..');
const SRC = path.join(ROOT, 'database/data/shelf_territories.json');
const OUT_DIR = path.join(ROOT, 'public/fonts/plaque');
const OUT_JSON = path.join(ROOT, 'resources/js/game/data/plaque_fonts.json');
const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0 Safari/537.36';

const data = JSON.parse(fs.readFileSync(SRC, 'utf8'));
const sets = new Map(); // id -> Set(chars)
const add = (id, text) => { if (!id || !text) return; const s = sets.get(id) ?? new Set(); [...nfc(text)].filter((ch) => ch.trim() && ch !== '·').forEach((ch) => s.add(ch)); sets.set(id, s); };
(data.factions ?? []).forEach((f) => {
    const p = f?.plaque; if (!p) return;
    if (p.native) add(plaqueFontId(p.native_script, p.native_lang), p.native);
    if (p.native && p.native_alt) add(plaqueFontId(p.native_alt_script, p.native_alt_lang), p.native_alt); // 현지 폰트 실패 시 대체 표기
    else if (p.text) add(plaqueFontId(p.script, ''), p.text); // native 없을 때만 표시되는 기존 표기
});
// 영웅 원어 이름(database/data/hero_native_names.json, 있을 때만): 뽑기 결과 카드 큰 이름(ui/GachaReveal) 글자도 같은 서브셋에 넣는다
{ const hn = path.join(ROOT, 'database/data/hero_native_names.json'); if (fs.existsSync(hn)) { const j = JSON.parse(fs.readFileSync(hn, 'utf8')); const src = j?.items && typeof j.items === 'object' ? j.items : (j?.heroes && typeof j.heroes === 'object' ? j.heroes : j); Object.entries(src ?? {}).forEach(([k, v]) => { if (!k.startsWith('_') && v?.native) add(plaqueFontId(v.script, v.lang), v.native); }); } }
process.argv.slice(2).forEach((a, i, arr) => { if (a === '--extra' && arr[i + 1]) { const [id, ...t] = arr[i + 1].split(':'); add(id, t.join(':')); } });

fs.mkdirSync(OUT_DIR, { recursive: true });
const out = { _note: 'generated by resources/js/game/tools/build_plaque_fonts.mjs — 수동 수정 금지', generated: new Date().toISOString(), fonts: {} };
const bufs = new Map(); const failed = [];
for (const [id, set] of sets) {
    const def = PLAQUE_FONTS[id]; if (!def) continue;
    const chars = [...set].sort().join('');
    // '·' 같은 구두점은 UI 폰트 폴백으로 충분. 공백은 text 에 넣어 공백 글리프 포함
    const url = `https://fonts.googleapis.com/css2?family=${encodeURIComponent(def.google)}:wght@${def.weight}&display=swap&text=${encodeURIComponent(`${chars} `)}`;
    try {
        const r1 = await fetch(url, { headers: { 'User-Agent': UA } });
        if (!r1.ok) throw new Error(`CSS HTTP ${r1.status}`);
        const css = await r1.text();
        const m = /src:\s*url\(([^)]+)\)\s*format\('woff2'\)/.exec(css);
        if (!m) throw new Error(`woff2 URL 없음: ${css.slice(0, 120)}`);
        const r2 = await fetch(m[1], { headers: { 'User-Agent': UA } });
        if (!r2.ok) throw new Error(`woff2 HTTP ${r2.status}`);
        const buf = Buffer.from(await r2.arrayBuffer());
        if (buf.length < 100 || buf.toString('latin1', 0, 4) !== 'wOF2') throw new Error('woff2 형식 아님');
        bufs.set(id, buf);
        out.fonts[id] = { file: `/fonts/plaque/${id}.woff2`, google: def.google, weight: def.weight, chars, bytes: buf.length };
        console.log(`[plaque-fonts] ${id} ${def.google} ${set.size}자 ${buf.length}B`);
    } catch (e) { failed.push(`${id}: ${e.message}`); }
}
// 하나라도 실패하면 아무것도 쓰지 않는다(기존 woff2·JSON 유지 — 런타임 서브셋과 글자 목록이 어긋나지 않게)
if (failed.length) { console.error(`[plaque-fonts] 실패 -> 기록 중단(기존 파일 유지):\n ${failed.join('\n ')}`); process.exit(1); }
bufs.forEach((buf, id) => fs.writeFileSync(path.join(OUT_DIR, `${id}.woff2`), buf));
fs.writeFileSync(OUT_JSON, `${JSON.stringify(out, null, 1)}\n`);
console.log('[plaque-fonts] ->', path.relative(ROOT, OUT_JSON));
